function setLang(lang) {
  localStorage.setItem('nts_lang', lang);
  document.documentElement.setAttribute('dir', lang === 'ar' ? 'rtl' : 'ltr');
  document.documentElement.setAttribute('lang', lang);

  // Toggle active class on lang buttons
  document.querySelectorAll('.lang-btn').forEach(btn => {
    const dataLang = btn.getAttribute('data-lang');
    const onClickStr = btn.getAttribute('onclick') || '';
    if (dataLang) {
      btn.classList.toggle('active', dataLang === lang);
    } else {
      btn.classList.toggle('active', onClickStr.includes(`'${lang}'`));
    }
  });

  // Translate all elements with data-i18n
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang] && translations[lang][key] !== undefined) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = translations[lang][key];
      } else if (el.tagName === 'SELECT') {
        // If it's a select, translate its first empty/default option
        const firstOpt = el.querySelector('option[value=""], option:not([value])');
        if (firstOpt) {
          firstOpt.textContent = translations[lang][key];
        }
      } else {
        el.innerHTML = translations[lang][key];
      }
    }
  });

  document.dispatchEvent(new CustomEvent('nts:languagechange', { detail: { lang } }));
}

// On page load, apply language preference
document.addEventListener('DOMContentLoaded', () => {
  const savedLang = localStorage.getItem('nts_lang') || 'en';
  setLang(savedLang);
});
